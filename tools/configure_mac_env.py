#!/usr/bin/env python3
"""Persist only this project's verified Android tool paths. Host bootstrap invokes this."""
import argparse
import os
from pathlib import Path
import shlex
import tempfile

START = '# >>> Magpie Android toolchain >>>'
END = '# <<< Magpie Android toolchain <<<'
LEGACY = '# Android SDK for Magpie Companion'
LEGACY_NAMES = ('export JAVA_HOME=', 'export ANDROID_HOME=', 'export ANDROID_SDK_ROOT=',
                'export GRADLE_USER_HOME=', 'export PATH=')


def merge_profile(text, block):
    lines, result = text.splitlines(), []
    inside, legacy = False, False
    for line in lines:
        if line == START:
            inside = True
            continue
        if inside:
            if line == END:
                inside = False
            continue
        if line == LEGACY:
            legacy = True
            continue
        if legacy and line.startswith(LEGACY_NAMES):
            continue
        legacy = False
        result.append(line)
    if inside:
        raise ValueError('Unclosed Magpie profile block; leaving profile unchanged')
    return '\n'.join(result).rstrip('\n') + '\n\n' + block + '\n'


def atomic_write(path, text, mode=0o600):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix='.magpie-env-', dir=path.parent)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as out:
            out.write(text)
        os.chmod(name, mode)
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def configure(home, sdk, java, manager, project):
    env_file = home / '.config/magpie-android/env.sh'
    env = '\n'.join((
        '# Generated by Magpie Android setup; no secrets are kept here.',
        'export JAVA_HOME=' + shlex.quote(str(java)),
        'export ANDROID_HOME=' + shlex.quote(str(sdk)),
        'export ANDROID_SDK_ROOT="$ANDROID_HOME"',
        'export GRADLE_USER_HOME="${GRADLE_USER_HOME:-$HOME/.gradle}"',
        'export PATH="$JAVA_HOME/bin:$ANDROID_HOME/platform-tools:$ANDROID_HOME/build-tools/36.0.0:"' +
        shlex.quote(str(manager.parent)) + ':"$PATH"', ''
    ))
    block = '\n'.join((START, '[ ! -r ' + shlex.quote(str(env_file)) + ' ] || . ' +
                       shlex.quote(str(env_file)), END))
    # Precompute profile changes before writing anything, preserving unowned settings.
    updates = []
    for filename in ('.zprofile', '.zshrc'):
        path = home / filename
        original = path.read_text(encoding='utf-8') if path.exists() else ''
        updated = merge_profile(original, block)
        updates.append((path, original, updated))
    atomic_write(env_file, env)
    for path, original, updated in updates:
        backup = path.with_name(path.name + '.pre-magpie-android.bak')
        if path.exists() and not backup.exists():
            atomic_write(backup, original)
        atomic_write(path, updated, path.stat().st_mode & 0o777 if path.exists() else 0o600)
    local = project / 'local.properties'
    prior = local.read_text(encoding='utf-8') if local.exists() else ''
    escaped = str(sdk).replace('\\', '\\\\').replace(':', '\\:').replace(' ', '\\ ').replace('=', '\\=')
    lines = [line for line in prior.splitlines() if not line.startswith('sdk.dir=')]
    atomic_write(local, '\n'.join(lines + ['sdk.dir=' + escaped, '']))
    return env_file


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for flag in ('sdk', 'java', 'manager', 'project'):
        parser.add_argument('--' + flag, type=Path, required=True)
    args = parser.parse_args()
    print('Environment file: ' + str(configure(Path.home(), args.sdk, args.java, args.manager, args.project)))
    print('zprofile/zshrc updated; prior settings backed up. Gradle uses the project wrapper, not a global Gradle installation.')


if __name__ == '__main__':
    main()
